def test_source_is_stdlib_only_and_ast_safety_audited() -> None:
    source = Path(__file__).read_text()
    tree = ast.parse(source)
    allowed_imports = {"__future__", "ast", "copy", "json", "re", "pathlib"}
    imports = {node.module.split(".")[0] for node in ast.walk(tree) if isinstance(node, ast.ImportFrom) and node.module}
    imports |= {alias.name.split(".")[0] for node in ast.walk(tree) if isinstance(node, ast.Import) for alias in node.names}
    assert imports <= allowed_imports
    forbidden_calls = {"open", "eval", "exec", "compile", "__import__", "write", "write_text", "write_bytes", "touch", "unlink", "rename", "replace"}
    forbidden_roots = {"os", "subprocess", "socket", "urllib", "http", "requests", "sqlite3", "duckdb", "importlib"}
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            name = node.func.id if isinstance(node.func, ast.Name) else node.func.attr if isinstance(node.func, ast.Attribute) else ""
            assert name not in forbidden_calls
        if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
            assert node.value.id not in forbidden_roots
            assert not (node.value.id == "os" and node.attr == "environ")
    read_calls = [node for node in ast.walk(tree) if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "read_text"]
    assert len(read_calls) == 3
    assert {ast.unparse(node.func.value) for node in read_calls} == {"DOC", "ALLOWLIST", "Path(__file__)"}
    assert "meg" + ".weather" not in source
