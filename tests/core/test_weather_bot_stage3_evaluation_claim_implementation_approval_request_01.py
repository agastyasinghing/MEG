def _parse(text: str) -> dict[str, object]:
    title = text.splitlines()[0].removeprefix("# ")
    canonical = re.search(r"^Canonical ID: (.+)$", text, re.MULTILINE)
    blocks = re.findall(r"```json\n(.*?)\n```", text, re.DOTALL)
    if canonical is None or len(blocks) != 1:
        raise ValueError("document shape")
    value = json.loads(blocks[0])
    if type(value) is not dict:
        raise ValueError("machine contract root")
    if title != value.get("title") or canonical.group(1) != value.get("canonical_id"):
        raise ValueError("identity disagreement")
    _validate(value)
    return value


def _validate(value: dict[str, object]) -> None:
    if value != EXPECTED:
        raise ValueError("contract drift")
    if len(value["public_symbols"]) != 8 or len(value["record_fields"]) != 34:
        raise ValueError("API cardinality")
    if len(value["validation_codes"]) != 38 or len(value["validation_groups"]) != 38:
        raise ValueError("validation cardinality")
    if value["required_mapping_keys"] != [field[0] for field in value["record_fields"][:33]]:
        raise ValueError("mapping field order")
    enum_codes = value["enums"]["EvaluationClaimValidationCode"]
    if enum_codes != [[code, code.lower()] for code in value["validation_codes"]]:
        raise ValueError("code enum disagreement")


def _mutate(path: tuple[object, ...], replacement: object) -> dict[str, object]:
    changed = copy.deepcopy(EXPECTED)
    target = changed
    for part in path[:-1]:
        target = target[part]
    target[path[-1]] = replacement
    return changed


